const assert = require('node:assert/strict');
const AgentTransport = require('../agent-transport');
let message, result;
const agent = { dbNodeKey:'node/a/1', send(s) { message=JSON.parse(s); } };
const transport = new AgentTransport(() => agent, 'echo ok', 'windows');
const handle=transport.start({node_id:agent.dbNodeKey},r=>{result=r;});
const id=message.attempt; assert.equal(message.op,'probe');
assert.equal(transport.receive({attempt:id,event:'ready'},{dbNodeKey:agent.dbNodeKey}),false);
assert.equal(transport.receive({attempt:id,event:'ready'},agent),true); assert.equal(message.op,'run');
handle.cancel(); assert.equal(message.op,'cancel');
assert.equal(transport.receive({attempt:id,event:'finished',exitCode:1,stderr:'error'},agent),true); assert.equal(result.exit_code,1);
transport.start({node_id:agent.dbNodeKey},r=>{result=r;}); transport.disconnected(agent); assert.equal(result.confirmed,true); assert.match(result.stderr,/before/);
transport.start({node_id:agent.dbNodeKey},r=>{result=r;}); transport.receive({attempt:message.attempt,event:'ready'},agent); transport.disconnected(agent); assert.equal(result.confirmed,false);
const noReply=new AgentTransport(()=>agent,'x','windows',null,{probeTimeout:10}); noReply.start({node_id:agent.dbNodeKey},r=>{assert.equal(r.confirmed,true);assert.match(r.stderr,/script was not sent/); console.log('Transport probe and disconnect checks passed');});
